// 05_models_guns4.js — v21 판처파우스트 (보급상자 전용 1회용 대전차 로켓) 3D 모델 · 자체 디자인
//  · 가는 올리브색 발사관 + 앞에 꽂힌 큰 탄두(회전체) · 위 가늠자 판(구멍 3개) · 붉은 발사 레버 · 아래 손잡이·방아쇠 · 앞 나무 손받침
//  · 탄두는 부품 'head' — 쏘면 숨겨져 빈 발사관만 남고, 날아가는 로켓(06_combat.js)도 같은 모양을 쓴다
//  좌표: +z 앞(탄두), +y 위, -x 오른쪽. 원점은 손잡이 위. 발사관 축 높이 boreY
// ============================================================
(() => {
  const { A, BX, CY, RB, PF, M, tube, trigger } = Models.kit;
  const G = Models.GUNS, BY = 0.07, R0 = 0.024;
  // 탄두 옆모습 (반지름, 앞뒤) — 뒤 원뿔 → 굵은 몸통 → 뾰족한 머리
  const HEAD = [[0.0, -0.004], [0.019, -0.004], [0.024, 0.0], [0.034, 0.018], [0.047, 0.04], [0.057, 0.066], [0.0625, 0.092], [0.064, 0.118], [0.063, 0.142], [0.058, 0.168], [0.049, 0.196], [0.037, 0.222], [0.024, 0.245], [0.013, 0.262], [0.006, 0.272], [0.0, 0.276]];
  const lathe = (pts, seg = 26) => { const g = new THREE.LatheGeometry(pts.map(([r, z]) => new THREE.Vector2(r, z)), seg); g.rotateX(Math.PI / 2); return g; };
  G.pzf = {
    meta: { railY: 0.14, scopeZ: 0.0, ironY: 0.147, ironRearZ: 0.075, ironRelief: 0.42, muzzleZ: 0.44, boreY: BY, headPos: [0, BY, 0.16], backZ: -0.42,
      gripPos: [0, -0.04, -0.058], forePos: [0.004, 0.02, 0.1], ejectPos: [0, BY, -0.42], hip: [0.13, -0.17, -0.5], noMag: true },
    body(g) {
      const od = M('anod', 0x434a2e), od2 = M('anod', 0x343a24), dk = M('gunmetal', 0x1b1c1a), rd = M('polymer', 0xb02a1e), yl = M('paper', 0xcdb04a), wd = M('wood', 0x6e4628), bk = M('polymer', 0x101010);
      // 발사관 (안이 빈 관) · 뒤 나팔 · 죔쇠 띠 2개
      tube(g, R0, R0 - 0.003, 0.58, od, 0, BY, -0.13, 22);
      A(g, CY(R0, R0 + 0.006, 0.034, 22, 'z', true), od2, 0, BY, -0.403);
      for (const z of [-0.3, -0.05]) A(g, CY(R0 + 0.0016, R0 + 0.0016, 0.012, 22), dk, 0, BY, z);
      A(g, CY(R0 + 0.0022, R0 + 0.0022, 0.016, 22), od2, 0, BY, 0.152);
      // 위 경고 표지 (노란 판 + 검은 줄) — 뒤 화염 주의
      A(g, BX(0.03, 0.0016, 0.13), yl, 0, BY + R0 - 0.0004, -0.26);
      for (let i = 0; i < 4; i++) A(g, BX(0.024, 0.0018, 0.006), bk, 0, BY + R0 + 0.0002, -0.31 + i * 0.03);
      A(g, BX(0.03, 0.0017, 0.012), rd, 0, BY + R0 - 0.0002, -0.185);
      // 발사 장치: 위 덮개 · 붉은 발사 레버 · 접어 올린 가늠자 판(구멍 3개)
      A(g, RB(0.022, 0.014, 0.07, 0.004), od2, 0, BY + R0 + 0.004, 0.02);
      A(g, BX(0.011, 0.006, 0.034), rd, 0, BY + R0 + 0.014, 0.034, -0.18, 0, 0);
      A(g, CY(0.004, 0.004, 0.024, 8, 'x'), dk, 0, BY + R0 + 0.006, 0.052);
      A(g, BX(0.028, 0.05, 0.003), od2, 0, BY + R0 + 0.025, 0.075);
      for (const y of [0.045, 0.033, 0.021]) A(g, BX(0.005, 0.005, 0.0034), bk, 0, BY + R0 + y, 0.075);   // 거리별 조준 구멍 (맨 위가 가늠쇠와 같은 높이)
      A(g, BX(0.04, 0.004, 0.006), dk, 0, BY + R0 + 0.002, 0.075);
      // 아래: 방아쇠 몸통 · 손잡이 · 방아쇠울
      A(g, RB(0.03, 0.026, 0.11, 0.006), od2, 0, BY - R0 - 0.01, -0.03);
      A(g, PF([[-0.074, 0.034], [-0.034, 0.034], [-0.05, -0.064], [-0.062, -0.078], [-0.08, -0.08], [-0.088, -0.066], [-0.08, 0.03]], 0.028, 0.004), M('polymer', 0x1d1f1b));
      for (let i = 0; i < 4; i++) A(g, BX(0.029, 0.003, 0.004), bk, 0, 0.01 - i * 0.02, -0.04 - i * 0.004, 0.16, 0, 0);
      trigger(g, -0.016, 0.034, dk);
      // 앞 나무 손받침 (탄두 바로 뒤)
      A(g, RB(0.034, 0.03, 0.1, 0.008), wd, 0, BY - R0 - 0.008, 0.095);
      for (let i = 0; i < 4; i++) A(g, BX(0.0345, 0.002, 0.004), M('wood', 0x4a2e1a), 0, BY - R0 - 0.0225, 0.06 + i * 0.024);
    },
    // 탄두 (부품 축 = 발사관 축). 뒤 꼬리대·접힌 날개는 관 안에 꽂혀 있다가 날아갈 때 보인다
    head(g) {
      const od = M('shell', 0x4c5432), dk = M('gunmetal', 0x262824), yl = M('paper', 0xd0ae38), st = M('metal', 0x8a8e88);   // shell: 스킨이 탄두만 따로 칠함 (평소엔 무광 올리브)
      A(g, CY(0.016, 0.016, 0.2, 14), dk, 0, 0, -0.1);
      for (let i = 0; i < 4; i++) { const a = i * Math.PI / 2 + Math.PI / 4; A(g, BX(0.0022, 0.012, 0.08), st, Math.cos(a) * 0.017, Math.sin(a) * 0.017, -0.16, 0, 0, a + Math.PI / 2); }
      A(g, lathe(HEAD), od);
      A(g, CY(0.0645, 0.0645, 0.012, 26), yl, 0, 0, 0.124);
      A(g, CY(0.0605, 0.0628, 0.006, 26), dk, 0, 0, 0.152);
      A(g, CY(0.007, 0.011, 0.016, 12), dk, 0, 0, 0.272);
      A(g, BX(0.004, 0.014, 0.005), dk, 0, 0.07, 0.118);
    },
  };
})();
