// 대형 렌치(파이프 렌치): 빨간 I 빔 자루(끝에 걸이 구멍) + 머리 틀 · 위 갈고리 턱과 아래 뒤꿈치 턱이 톱니를 마주 보고 입은 -y 로 열린다 · 틀 창 속 톱니 조절 너트
MSHAPE.wrench = { melee: 'crowbar', tip: 0.44, build(g, K, S) {
  const { put, M, BX, CY, PF, slab, circlePts } = K;
  const rd = M('polymer', 0xb02a20), jw = M('gunmetal', 0x5b5f64), th = M('metal', 0xc2c6ca), nt = M('metal', 0xa3a7ac), sh = M('gunmetal', 0x45484d);
  // 자루 끝: 걸이 구멍 뚫린 둥근 판 — slab(위에서 본 판)을 z 축으로 돌려 옆모습(y-z) 판으로 (점 = [y, z])
  put(g, slab([[-0.0158, -0.19], [-0.0158, -0.222], [-0.012, -0.236], [-0.0045, -0.2435], [0.0045, -0.2435], [0.012, -0.236], [0.0158, -0.222], [0.0158, -0.19]], 0.019, 0.0012, [circlePts(0, -0.221, 0.0062, 10)]).rotateZ(Math.PI / 2), rd);
  // I 빔: 얇은 가운데 판 + 위아래 넓은 날개 (머리 쪽에서 틀로 벌어짐)
  put(g, PF([[-0.2, -0.0145], [0.205, -0.0185], [0.262, -0.03], [0.28, -0.03], [0.28, 0.038], [0.262, 0.038], [0.205, 0.0195], [-0.2, 0.0145]], 0.009), rd);
  put(g, PF([[-0.2, -0.0145], [0.205, -0.0185], [0.262, -0.0305], [0.266, -0.025], [0.205, -0.0128], [-0.2, -0.0088]], 0.021), rd);
  put(g, PF([[-0.2, 0.0145], [0.205, 0.0195], [0.262, 0.0385], [0.266, 0.032], [0.205, 0.0138], [-0.2, 0.0088]], 0.021), rd);
  // 머리 틀: 아래·위 덩어리 + 앞(-y)·뒤 기둥 → 가운데 창에 너트 · 옆으로 보이는 핀 둘
  put(g, BX(0.03, 0.076, 0.028), rd, 0, 0.005, 0.279);
  put(g, BX(0.03, 0.076, 0.016), rd, 0, 0.005, 0.343);
  put(g, BX(0.03, 0.0125, 0.06), rd, 0, -0.02675, 0.314);
  put(g, BX(0.03, 0.012, 0.06), rd, 0, 0.037, 0.314);
  for (const [y, z] of [[-0.027, 0.3], [0.03, 0.279]]) put(g, CY(0.0042, 0.0042, 0.033, 8, 'x'), nt, 0, y, z);
  // 갈고리 턱 자루(틀을 꿰뚫고 아래로 조금 나옴) + 조절 너트: 톱니 24 개 별 모양 판을 z 축으로 세움 (겉에 세로 홈 = 널링)
  put(g, CY(0.0078, 0.0078, 0.15, 8, 'z'), sh, 0, 0.008, 0.33);
  const np = []; for (let i = 0; i < 24; i++) { const a = i / 24 * TAU, r = i % 2 ? 0.0188 : 0.0205; np.push([Math.cos(a) * r, Math.sin(a) * r]); }
  put(g, slab(np, 0.034, 0).rotateX(Math.PI / 2), nt, 0, 0.008, 0.314);
  // 턱: 위 갈고리 턱(뒤 기둥 + 앞으로 뻗은 팔) · 아래 뒤꿈치 턱(틀 앞에 박힘)
  put(g, PF([[0.35, 0.022], [0.43, 0.022], [0.442, 0.01], [0.442, -0.066], [0.434, -0.08], [0.412, -0.082], [0.412, -0.004], [0.35, -0.004]], 0.024), jw);
  put(g, PF([[0.338, -0.006], [0.338, -0.058], [0.347, -0.075], [0.364, -0.079], [0.364, -0.006]], 0.024), jw);
  // 톱니 띠 (밑변 zb · 골 zv · 이 끝 zt, y0 → y1 에 n 개, k = 이 끝 자리): 위 턱은 -z 로 · 아래 턱은 +z 로 이가 나 서로 마주 본다
  const teeth = (zb, zv, zt, y0, y1, n, k) => { const p = (y1 - y0) / n, o = [[zb, y1], [zb, y0], [zv, y0]]; for (let i = 0; i < n; i++) o.push([zt, y0 + (i + k) * p], [zv, y0 + (i + 1) * p]); return o; };
  put(g, PF(teeth(0.414, 0.408, 0.401, -0.081, -0.004, 6, 0.35), 0.0225, 0.0005), th);
  put(g, PF(teeth(0.362, 0.369, 0.377, -0.079, -0.006, 6, 0.65), 0.0225, 0.0005), th);
} };

// 전쟁 망치: 검은 쇠 팔각 자루 + 가죽 끈 감은 손잡이 + 금 띠 · 무거운 머리 — 아래(-y) 평평한 네모 망치 면 · 위(+y) 손 쪽으로 휜 부리 가시 · 끝(+z) 짧은 가시
//  머리에서 자루 양옆(±x)으로 내려오는 쇠 띠(랑게트)와 금 리벳 · 금 자루끝
MSHAPE.warhammer = { melee: 'crowbar', tip: 0.45, build(g, K, S) {
  const { put, M, BX, CY, PF, SPH, lathe } = K;
  const sf = M('gunmetal', 0x3a3c40), hd = M('gunmetal', 0x575b61), st = M('metal', 0xa9adb2), fc = M('metal', 0xc4c8cd), au = M('brass', 0xc9a24a);
  const oc = (geo) => geo.rotateZ(Math.PI / 8);   // 팔각 단면: 평평한 면이 ±x·±y 로 (랑게트가 면에 붙게)
  put(g, oc(CY(0.0115, 0.0115, 0.635, 8, 'z')), sf, 0, 0, 0.0825);   // 자루 z -0.235 ~ 0.4
  put(g, oc(lathe([[0, -0.268], [0.008, -0.266], [0.0165, -0.255], [0.0185, -0.243], [0.015, -0.232], [0.0125, -0.224]], 8, 'z')), au);   // 금 자루끝
  // 가죽 끈: 같은 쪽으로 기운 고리 8 개를 이어 비스듬히 감은 것처럼 (사이 틈이 끈 자국)
  for (let i = 0; i < 8; i++) put(g, oc(CY(0.0138, 0.0138, 0.0215, 8, 'z')), M('cloth', i % 2 ? 0x5a3a22 : 0x4f321d), 0, 0, -0.077 + i * 0.022, 0.14);
  for (const z of [-0.093, 0.093, -0.22]) put(g, oc(CY(0.0148, 0.0148, 0.008, 8, 'z')), au, 0, 0, z);
  put(g, oc(CY(0.0158, 0.0158, 0.01, 8, 'z')), au, 0, 0, 0.352);   // 머리 밑 금 띠 (랑게트 위로 감음)
  for (const s of [-1, 1]) put(g, PF([[0.372, -0.0065], [0.235, -0.0055], [0.215, 0], [0.235, 0.0055], [0.372, 0.0065]], 0.003, 0.0005), st, s * 0.0121, 0, 0);
  for (const z of [0.25, 0.31]) put(g, CY(0.0026, 0.0026, 0.029, 6, 'x'), au, 0, 0, z);
  // 머리 몸통 + 위아래 금 테 · 옆 금 징
  put(g, BX(0.032, 0.04, 0.06), hd, 0, 0, 0.393);
  for (const z of [0.366, 0.42]) put(g, BX(0.034, 0.042, 0.006), au, 0, 0, z);
  for (const s of [-1, 1]) put(g, SPH(0.0042, 6, 4), au, s * 0.016, 0, 0.393);
  // 망치(-y): 면 쪽으로 굵어지는 네모 목 + 평평한 네모 면(맨 강철, 가운데가 살짝 도드라짐)
  put(g, new THREE.CylinderGeometry(0.02, 0.0265, 0.04, 4).rotateY(Math.PI / 4), hd, 0, -0.039, 0.393);
  put(g, BX(0.042, 0.014, 0.042), fc, 0, -0.0655, 0.393);
  put(g, BX(0.036, 0.004, 0.036), fc, 0, -0.074, 0.393);
  // 부리 가시(+y): 마름모 단면 뿔을 높이를 따라 반지름 rho 인 호로 굽혀 끝이 손 쪽(-z)으로 휜다 (꺾인 마디 없이 매끈하게 · 면은 각지게)
  //  밑면 가운데 = 원점 → 높이 y 의 점은 휜 중심(z = -rho)을 y / rho 만큼 돈 자리로
  const horn = (rb, h, rho, n) => { const geo = new THREE.CylinderGeometry(0.0008, rb, h, 4, n).toNonIndexed(); geo.translate(0, h / 2, 0); geo.scale(0.75, 1, 1); const p = geo.attributes.position; for (let i = 0; i < p.count; i++) { const y = p.getY(i), z = p.getZ(i), f = y / rho; p.setXYZ(i, p.getX(i), (rho + z) * Math.sin(f), (rho + z) * Math.cos(f) - rho); } geo.computeVertexNormals(); return geo; };
  put(g, horn(0.0205, 0.1, 0.18, 6), st, 0, 0.018, 0.393);
  // 끝 가시(+z) + 금 받침
  put(g, new THREE.CylinderGeometry(0.0008, 0.011, 0.05, 4).rotateX(Math.PI / 2), st, 0, 0, 0.448);
  put(g, oc(CY(0.0125, 0.0125, 0.006, 8, 'z')), au, 0, 0, 0.426);
} };

// 사탕 지팡이: 곧은 자루 + 끝에서 -y 로 굽는 둥근 갈고리(반원보다 조금 더 감김) · 빨강·흰 나선 줄무늬 · 갈고리 바로 밑 초록 리본
//  관은 직접 짠다: 중심선을 따라 8각 단면을 PITCH 마다 한 바퀴씩 비틀며 이으면 단면의 띠 j 하나하나가 나선이 된다
//  → 띠마다 빨강/흰 메시에 나눠 담아 경계가 깔끔한 줄무늬 · 양 끝은 평평한 단면(줄무늬 색 그대로 부채꼴)
MSHAPE.candy = { melee: 'crowbar', tip: 0.42, build(g, K, S) {
  const { put, M, CY, PF, SPH, TOR } = K;
  const NR = 8, PITCH = 0.12, CR = 0.016, Z0 = -0.24, ZH = 0.335, HR = 0.05, AE = Math.PI + 0.4, RED = [0, 1, 4];   // 빨간 띠: 굵은 줄(0·1) + 가는 줄(4)
  const L1 = ZH - Z0, L = L1 + HR * AE, NS = Math.ceil(L / (PITCH / NR));   // 한 마디에 띠 하나 폭까지만 비틀어 면이 꺾여 들어가지 않게
  // 중심선 s → [중심 x, y, z, 법선 N(y, z), 접선 T(y, z)] (종법선 B = +x) — 자루는 +z 로 곧게, 갈고리는 (0, -HR, ZH) 를 중심으로 돈다
  const at = (s) => { if (s <= L1) return [0, 0, Z0 + s, -1, 0, 0, 1]; const a = (s - L1) / HR, c = Math.cos(a), n = Math.sin(a); return [0, -HR + HR * c, ZH + HR * n, -c, -n, -n, c]; };
  const V = [];
  for (let i = 0; i <= NS; i++) {
    const s = L * i / NS, f = at(s), row = [];
    for (let j = 0; j <= NR; j++) { const t = (j / NR + s / PITCH) * TAU, nx = Math.sin(t), ny = Math.cos(t) * f[3], nz = Math.cos(t) * f[4]; row.push([f[0] + CR * nx, f[1] + CR * ny, f[2] + CR * nz, nx, ny, nz]); }
    V.push(row);
  }
  const pos = [[], []], nor = [[], []], col = (j) => (RED.includes(j) ? 0 : 1);
  const push = (k, v, n) => { pos[k].push(v[0], v[1], v[2]); nor[k].push(n[0], n[1], n[2]); };
  // 옆면: 마디 i · 띠 j 의 사각형 = 삼각형 둘 (밖에서 보아 반시계)
  for (let i = 0; i < NS; i++) for (let j = 0; j < NR; j++) { const a = V[i][j], b = V[i][j + 1], c = V[i + 1][j], d = V[i + 1][j + 1], k = col(j); for (const v of [a, b, c, b, d, c]) push(k, v, [v[3], v[4], v[5]]); }
  // 양 끝 평평한 단면: 아래 끝은 -T, 갈고리 끝은 +T 를 보게 감는다
  for (const [i, sg] of [[0, -1], [NS, 1]]) {
    const f = at(L * i / NS), o = [f[0], f[1], f[2]], tn = [0, f[5] * sg, f[6] * sg];
    for (let j = 0; j < NR; j++) { const k = col(j), a = V[i][j], b = V[i][j + 1]; if (sg > 0) { push(k, o, tn); push(k, a, tn); push(k, b, tn); } else { push(k, o, tn); push(k, b, tn); push(k, a, tn); } }
  }
  const mk = (k) => { const geo = new THREE.BufferGeometry(); geo.setAttribute('position', new THREE.Float32BufferAttribute(pos[k], 3)); geo.setAttribute('normal', new THREE.Float32BufferAttribute(nor[k], 3)); return geo; };
  put(g, mk(0), M('anod', 0xf01822)); put(g, mk(1), M('polymer', 0xf6f3ee));   // 빨강은 반광(사탕 윤기) · 흰색은 밝게
  // 초록 리본: 자루를 감은 띠 + 옆(-x)의 매듭 · 위로 살짝 들린 고리 둘 · 끝이 V 로 파인 꼬리 둘 (리본 면은 y-z — 옆모습에서 잘 보이고 고리는 자루 밖으로 삐져나와 반대쪽에서도 보임)
  const gr = M('polymer', 0x1f8f3e), ZB = 0.3, XB = -0.0195;
  put(g, CY(0.0178, 0.0178, 0.012, 8, 'z'), gr, 0, 0, ZB);
  put(g, SPH(0.0075, 6, 4).scale(0.7, 1, 1.1), gr, XB, 0, ZB);
  for (const s of [-1, 1]) {
    put(g, TOR(0.015, 0.0036, 4, 8).scale(0.8, 1.35, 0.7).rotateY(Math.PI / 2), gr, XB - 0.001, s * 0.0215, ZB + 0.004, s * 0.35);
    put(g, PF([[0.2952, -0.0001], [0.2432, 0.0219], [0.2505, 0.0237], [0.2468, 0.0301], [0.2988, 0.0081]].map(([z, y]) => [z, y * s]), 0.0035, 0.0006), gr, XB);
  }
} };
