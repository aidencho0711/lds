// 손잡이 한 쪽: sd = −1(A) / +1(B) · (oy, oz) = 좌표를 옮김(B 는 핀 기준)
function bfHandle(g, K, sd, oy, oz) {
  const { put, M, BX, slab } = K, { YC, T, B, ZP, ZB } = BF, r = T - YC;
  const AN = [0x2e6be6, 0x7b45e8, 0xd03fa8, 0xe3b03a].map((c) => M('metal', c));
  const Z1 = ZB + 0.035, Z2 = Z1 + 0.035, Z3 = Z2 + 0.035;
  const hole = (z0, z1) => [[YC, z0 + 0.0042], [YC + 0.007, z0 + 0.0085], [YC + 0.007, z1 - 0.0085], [YC, z1 - 0.0042], [YC - 0.007, z1 - 0.0085], [YC - 0.007, z0 + 0.0085]];
  const arc = []; for (let i = 0; i <= 8; i++) { const a = i / 8 * Math.PI; arc.push([YC + r * Math.cos(a), ZP + r * Math.sin(a)]); }   // 앞 끝: 핀을 감싸는 반원(위 → 앞 → 아래)
  // 토막 윤곽 [y, z] → 판을 z 축으로 90° 돌려 y-z 평면에 세움(두께 = x) · 뒤 토막은 모서리를 깎고, 앞 토막은 핀 둘레를 둥글게
  //  날개: 옆판 안쪽 위·아래 가장자리를 따라 가운데로 접힌 띠(같은 색) → 위·아래에서 보면 ㄷ자 홈통, 사이로 날이 들어갈 틈
  const SEG = [
    [[B, Z1], [T, Z1], [T, ZB + 0.0035], [YC + 0.0075, ZB], [YC - 0.007, ZB], [B, ZB + 0.0035]],
    [[B, Z2], [T, Z2], [T, Z1], [B, Z1]],
    [[B, Z3], [T, Z3], [T, Z2], [B, Z2]],
    [[B, Z3], [T, Z3]].concat(arc),
  ], HZ = [[ZB + 0.0035, Z1], [Z1, Z2], [Z2, Z3], [Z3, ZP - 0.006]];
  const mv = (P) => P.map(([y, z]) => [y + oy, z + oz]);
  for (let k = 0; k < 4; k++) {
    const geo = slab(mv(SEG[k]), 0.0055, 0, [mv(hole(HZ[k][0], HZ[k][1]))]), z0 = k === 0 ? ZB + 0.002 : HZ[k][0], z1 = k === 3 ? ZP : HZ[k][1];
    put(g, geo, AN[k], sd * 0.0088, 0, 0, 0, 0, Math.PI / 2);
    for (const y of [T - 0.0011, B + 0.0011]) put(g, BX(0.0031, 0.0022, z1 - z0), AN[k], sd * 0.0047, y + oy, (z0 + z1) / 2 + oz);
  }
}
