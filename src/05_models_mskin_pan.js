// 진저브레드 팬: 머리 = 납작하게 누운 진저브레드 맨 쿠키(머리 +z · 팔 ±x · 다리는 손잡이 쪽) · 하얀 아이싱 테두리·눈·웃는 입 · 젤리 단추 · 빨강·흰 사탕 막대 손잡이
MSHAPE.ginger = { melee: 'pan', tip: 0.43, build(g, K, S) {
  const { put, M, CY, SPH, slab, tubeAlong } = K;
  const ck = M('wood', 0x9a5a2a), ic = M('polymer', 0xf6f2ea), y0 = 0.004, top = y0 + 0.012;
  const arc = (cx, cz, r, a0, a1, n) => { const o = []; for (let i = 0; i <= n; i++) { const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180; o.push([cx + Math.cos(a) * r, cz + Math.sin(a) * r]); } return o; };   // 원호 점 (도 단위, n 조각)
  // 쿠키 윤곽 오른쪽 절반(머리 꼭대기 → 가랑이): 머리 원(0, 0.372 · r 0.058) · 손 원(0.106, 0.281 · 0.028) · 발 원(0.064, 0.147 · 0.03) → 좌우 대칭 전체
  const RH = [].concat(arc(0, 0.372, 0.058, 90, -40, 6), [[0.03, 0.318], [0.046, 0.311]], arc(0.106, 0.281, 0.028, 90, -90, 4), [[0.05, 0.252], [0.056, 0.205]], arc(0.064, 0.147, 0.03, 30, -150, 4), [[0.022, 0.172], [0, 0.19]]);
  const P = RH.concat(RH.slice(1, -1).reverse().map(([x, z]) => [-x, z]));
  put(g, slab(P, 0.024, 0.003), ck, 0, y0, 0);   // 쿠키 (두께 0.024 · 둥글린 가장자리)
  // 아이싱 테두리: 윤곽을 0.009 안으로 줄인 길(꼭짓점마다 양 옆 변의 안쪽 법선 평균 방향 — 마이터)을 따라 윗면에 얹은 관
  const n = P.length; let ar = 0; for (let i = 0; i < n; i++) { const p = P[i], q = P[(i + 1) % n]; ar += p[0] * q[1] - q[0] * p[1]; }
  const sg = ar > 0 ? 1 : -1, nv = (a, b) => { const ex = b[0] - a[0], ez = b[1] - a[1], l = Math.hypot(ex, ez) || 1; return [-ez / l * sg, ex / l * sg]; };
  const ice = P.map((p, i) => {
    const n1 = nv(P[(i + n - 1) % n], p), n2 = nv(p, P[(i + 1) % n]); let mx = n1[0] + n2[0], mz = n1[1] + n2[1]; const ml = Math.hypot(mx, mz) || 1; mx /= ml; mz /= ml;
    const k = 0.009 / Math.max(0.35, mx * n1[0] + mz * n1[1]); return [p[0] + mx * k, top + 0.0004, p[1] + mz * k];
  });
  put(g, tubeAlong(ice, 0.0035, 56, 4, true), ic);
  // 눈 · 웃는 입 (입 양 끝은 쿠키 속으로 파고들어 관 끝이 안 보인다)
  for (const x of [-0.019, 0.019]) { const e = SPH(0.0062, 6, 3); e.scale(1, 0.55, 1); put(g, e, ic, x, top + 0.0005, 0.385); }
  put(g, tubeAlong([[-0.026, top - 0.004, 0.362], [-0.022, top + 0.0004, 0.358], [-0.012, top + 0.0004, 0.3495], [0, top + 0.0004, 0.3468], [0.012, top + 0.0004, 0.3495], [0.022, top + 0.0004, 0.358], [0.026, top - 0.004, 0.362]], 0.0028, 8, 4), ic);
  // 젤리 단추 3개 (빨강·초록·빨강 반구, 밑은 쿠키에 살짝 묻힘)
  [[0.291, 0xd8202a], [0.257, 0x2aa040], [0.223, 0xd8202a]].forEach(([z, col]) => { const d = SPH(0.0105, 6, 3, 0, Math.PI / 2); d.scale(1, 0.9, 1); put(g, d, M('polymer', col), 0, top - 0.0008, z); });
  // 손잡이: 빨강·흰 마디 7개 사탕 막대(z -0.085 ~ 0.205, 가랑이 사이로 쿠키 속까지) + 뒤 끝 둥근 마개
  const red = M('polymer', 0xd8202a), wh = M('polymer', 0xf4f0ea), L = 0.0414;
  for (let i = 0; i < 7; i++) put(g, CY(0.0112, 0.0112, L, 8, 'z', true), i % 2 ? red : wh, 0, y0, -0.085 + L * (i + 0.5));
  put(g, CY(0.0112, 0.0075, 0.007, 8, 'z'), red, 0, y0, -0.0885);
} };
